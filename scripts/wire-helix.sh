#!/usr/bin/env bash
# Wire the hobby HMML language server into Helix, on any machine.
#
# THE MODEL
# ---------
# Helix reads ~/.config/helix/languages.toml and *merges* it over the languages.toml
# compiled into the binary. Two inputs, so two files here:
#
#   <checkout>/languages.toml               machine-NEUTRAL, committed, shared by every
#                                           machine, and the file the binary is built from
#   ~/.config/helix/languages.local.toml    machine-SPECIFIC, generated here, never committed
#
# and one output:
#
#   ~/.config/helix/languages.toml          = neutral + local, regenerated by this script
#
# The split exists because of one line. `[[grammar]] name = "mml"` needs an absolute
# `source.path` to a tree-sitter-mml checkout, which is work code and lives at a
# different path — or nowhere — on each machine. Committing that path to the shared
# branch breaks `cargo install --path helix-term` on every other machine, because
# helix-term/build.rs builds grammars with STRICT = true and one unbuildable grammar
# fails the entire binary build. Keeping the line out of git and generating it per
# machine makes both machines correct with no per-machine edits to undo.
#
# Everything else — the hmml language, the server registration, the queries — is
# machine-neutral and goes in the checkout.
#
# Idempotent: re-running re-derives the same output and reports no change.
#
# Usage: wire-helix.sh [helix-checkout]
#        HELIX_REPO=/path/to/helix wire-helix.sh
#        TREE_SITTER_MML=/path/to/tree-sitter-mml wire-helix.sh

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=./helix-paths.sh
source "$HERE/helix-paths.sh"

[ -n "${1:-}" ] && HELIX_REPO="$1"

if ! resolve_repo; then
    echo "wire-helix: no Helix checkout found." >&2
    echo "  Looked at \$HELIX_REPO, the ~/.config/helix/runtime symlink, and" >&2
    echo "  ~/{fun_repos,outside_repos,projects,src,repos}/helix." >&2
    echo "  Pass the checkout as an argument or set HELIX_REPO." >&2
    echo "  Skipping Helix wiring — hwt/hcdev/skills all work without it." >&2
    exit 0
fi

REPO="$HELIX_REPO_RESOLVED"
CFG="$HELIX_CFG"
LANGS="$REPO/languages.toml"
LOCAL="$CFG/languages.local.toml"
INSTALLED="$CFG/languages.toml"
QUERIES="$REPO/runtime/queries/hmml"
LEGACY_QUERIES="$REPO/runtime/queries/mml-hobby"

echo "  Helix checkout: $REPO (via $HELIX_REPO_WHY)"

changed=0

# --- 0. drop the pre-.hmml `mml-hobby` language ------------------------------
# Before the rename, both dialects claimed `.mml` and hobby specs were singled
# out by the path glob `**/hobby-mimisbrunnr/notes/**/*.mml`. That entry is dead
# now and would fight the `hmml` block below for any `.mml` file, so remove it.
# Guarded on presence: a fresh machine no-ops straight through.
if grep -q '^name = "mml-hobby"$' "$LANGS"; then
    awk '
      NR == FNR { line[FNR] = $0; n = FNR; if ($0 ~ /^name = "mml-hobby"$/) hit = FNR; next }
      FNR == 1 {
        # Walk back to the [[language]] header, then over its comment preamble.
        h = hit; while (h > 1 && line[h] !~ /^\[\[language\]\]$/) h--
        s = h;   while (s > 1 && line[s - 1] ~ /^#/) s--
        # Forward to the line before the next top-level header, plus any blanks.
        e = h + 1; while (e <= n && line[e] !~ /^\[/) e++
        e--
        while (e < n && line[e + 1] == "") e++
        for (i = 1; i <= n; i++) if (i < s || i > e) print line[i]
      }
    ' "$LANGS" "$LANGS" > "$LANGS.tmp"
    mv "$LANGS.tmp" "$LANGS"
    echo "  languages.toml: removed the legacy glob-routed mml-hobby language"
    changed=1
fi
if [ -d "$LEGACY_QUERIES" ]; then
    rm -rf "$LEGACY_QUERIES"
    echo "  queries: removed legacy mml-hobby/"
    changed=1
fi

# --- 1. evict the machine-specific mml grammar from the shared file ----------
# It moves to languages.local.toml in step 4. Any absolute source.path committed
# here is a path that exists on exactly one machine and breaks `cargo install
# --path helix-term` on the rest, so the shared file must not carry one.
if grep -A1 '^\[\[grammar\]\]$' "$LANGS" | grep -q '^name = "mml"$'; then
    awk '
      NR == FNR { line[FNR] = $0; n = FNR; next }
      FNR == 1 {
        for (i = 1; i <= n; i++) {
          # An [[grammar]] header whose next line is the mml name: skip the block,
          # its comment preamble, and the blank lines that followed it.
          if (line[i] == "[[grammar]]" && line[i + 1] == "name = \"mml\"") {
            while (out > 0 && kept[out] ~ /^#/) out--
            j = i + 1
            while (j < n && line[j + 1] !~ /^\[/ && line[j + 1] != "") j++
            while (j < n && line[j + 1] == "") j++
            i = j
            continue
          }
          kept[++out] = line[i]
        }
        for (i = 1; i <= out; i++) print kept[i]
      }
    ' "$LANGS" "$LANGS" > "$LANGS.tmp"
    mv "$LANGS.tmp" "$LANGS"
    echo "  languages.toml: moved the mml grammar out of the shared file (it is machine-specific)"
    changed=1
fi

# --- 2. language-server entry ------------------------------------------------
if grep -q '^hobby-mml-lsp = ' "$LANGS"; then
    echo "  languages.toml: hobby-mml-lsp server already registered"
else
    # Insert directly after the work mml-lsp entry so the two sit together.
    if grep -q '^mml-lsp = ' "$LANGS"; then
        sed -i '/^mml-lsp = /a hobby-mml-lsp = { command = "hobby-mml-lsp" }' "$LANGS"
    else
        sed -i '/^\[language-server\]/a hobby-mml-lsp = { command = "hobby-mml-lsp" }' "$LANGS"
    fi
    echo "  languages.toml: registered hobby-mml-lsp"
    changed=1
fi

# --- 3. the hmml language, routed by extension -------------------------------
# No ordering constraint: `hmml` and `mml` claim disjoint file types, so this can
# simply be appended. (Before the rename both claimed `.mml` and this block had
# to be spliced in above the `mml` entry to win.)
#
# Unconditional, unlike before: this used to bail out when the machine had no
# `mml` language, which left hobby-only machines with no HMML server at all. A
# `grammar = "mml"` naming a grammar that does not exist costs only syntax
# highlighting — the LSP, diagnostics and goto-definition all still work.
if grep -q '^name = "hmml"$' "$LANGS"; then
    echo "  languages.toml: hmml language already present"
else
    cat >> "$LANGS" <<'TOML'

# Hobby specs are `.hmml` and get the forked server, which resolves spec->source
# against ~/fun_worktrees/<project>/<topic>/<task> rather than the work layout
# ~/worktrees/<topic>/<task>/<repo>. `grammar = "mml"` reuses the tree-sitter
# grammar declared in ~/.config/helix/languages.local.toml, so there is no second
# grammar to build. Machines without that grammar lose highlighting only.
[[language]]
name = "hmml"
scope = "source.hmml"
injection-regex = "hmml"
file-types = ["hmml"]
comment-token = "#"
indent = { tab-width = 2, unit = "  " }
grammar = "mml"
language-servers = ["hobby-mml-lsp"]
TOML
    echo "  languages.toml: added hmml language (routed by the .hmml extension)"
    changed=1
fi

# --- 4. the machine-local overlay --------------------------------------------
# Rewritten from scratch every run, between markers, so the block tracks a moved
# or deleted grammar checkout instead of going stale. Anything you add outside
# the markers is preserved.
mkdir -p "$CFG"
BEGIN='# >>> hobby-tooling: mml grammar (generated — edit wire-helix.sh, not this) >>>'
END='# <<< hobby-tooling: mml grammar <<<'

local_body=""
[ -f "$LOCAL" ] && local_body=$(awk -v b="$BEGIN" -v e="$END" '
    $0 == b { skip = 1 } !skip { print } $0 == e { skip = 0 }' "$LOCAL")

if resolve_grammar_mml; then
    block=$(printf '%s\n[[grammar]]\nname = "mml"\nsource = { path = "%s" }\n%s' \
        "$BEGIN" "$MML_GRAMMAR_RESOLVED" "$END")
    if [ -n "$local_body" ]; then
        new_local=$(printf '%s\n\n%s' "$local_body" "$block")
    else
        new_local="$block"
    fi
    echo "  local overlay: mml grammar -> $MML_GRAMMAR_RESOLVED"
else
    new_local="$local_body"
    echo "  local overlay: no tree-sitter-mml on this machine — no grammar declared"
    echo "                 (.hmml keeps the LSP; it loses syntax highlighting only)"
fi

# Keep a header on an otherwise-empty overlay so the file explains itself.
if [ -z "$(printf '%s' "$new_local" | tr -d '[:space:]')" ]; then
    new_local='# Machine-specific Helix language config, generated by hobby-tooling.
# Merged into ~/.config/helix/languages.toml by `just wire-helix`. Not committed
# anywhere — this is the file that is allowed to hold absolute paths.'
fi

if [ -f "$LOCAL" ] && [ "$new_local" = "$(cat "$LOCAL")" ]; then
    :
else
    printf '%s\n' "$new_local" > "$LOCAL"
    changed=1
fi

# --- 5. generate the installed languages.toml --------------------------------
# neutral + local. A symlink here would defeat the generation, so say so instead
# of silently clobbering it.
if [ -L "$INSTALLED" ]; then
    echo "  NOTE: $INSTALLED is a symlink, so the generated merge cannot be installed."
    echo "        Remove it and re-run to let wire-helix manage the file."
else
    generated=$(mktemp)
    trap 'rm -f "$generated"' EXIT
    cat "$LANGS" > "$generated"
    printf '\n' >> "$generated"
    cat "$LOCAL" >> "$generated"
    if cmp -s "$generated" "$INSTALLED"; then
        echo "  ~/.config/helix/languages.toml already up to date"
    else
        cp "$generated" "$INSTALLED"
        echo "  generated $INSTALLED (checkout + local overlay)"
        changed=1
    fi
fi

# --- 6. highlight queries ----------------------------------------------------
# Helix resolves queries by *language name*, not grammar, so hmml needs its own
# directory even though it reuses the mml grammar. Without this, hobby specs
# parse but render unhighlighted.
if [ -f "$QUERIES/highlights.scm" ]; then
    echo "  queries: hmml/highlights.scm already present"
else
    mkdir -p "$QUERIES"
    cat > "$QUERIES/highlights.scm" <<'SCM'
; HMML highlighting.
;
; `hmml` is the same grammar as `mml` — it is a separate Helix language so that
; `.hmml` files reach the forked `hobby-mml-lsp`, which resolves spec->source
; against ~/fun_worktrees instead of ~/worktrees. Helix looks queries up by
; *language name*, not by grammar, so without this file hobby specs would render
; unhighlighted even though `grammar = "mml"` gives them the right parser.
;
; Inherit rather than copy, so the two stay in sync.
; inherits: mml
SCM
    echo "  queries: wrote hmml/highlights.scm"
    changed=1
fi

# --- 7. runtime symlink ------------------------------------------------------
# Queries are written into the checkout, so Helix only sees them through this link.
# Creating it is also what lets the resolver find the checkout on the next run.
if [ -L "$CFG/runtime" ]; then
    have=$(readlink -f "$CFG/runtime")
    if [ "$have" != "$(readlink -f "$REPO/runtime")" ]; then
        echo "  NOTE: $CFG/runtime points at $have, not $REPO/runtime."
        echo "        Queries written above are invisible to Helix until that is fixed."
    fi
elif [ -d "$CFG/runtime" ]; then
    echo "  NOTE: $CFG/runtime is a real directory, not a symlink into $REPO."
    echo "        Copy the queries yourself:  cp -r $QUERIES $CFG/runtime/queries/"
    echo "        And drop the stale one:     rm -rf $CFG/runtime/queries/mml-hobby"
else
    ln -s "$REPO/runtime" "$CFG/runtime"
    echo "  linked $CFG/runtime -> $REPO/runtime"
    changed=1
fi

if [ "$changed" -eq 0 ]; then
    echo "  Helix already wired; nothing to do."
else
    echo "  Helix wired. Verify:  hx --health hmml"
fi
